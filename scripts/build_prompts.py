def to_roman(number):
    result = []
    for value, symbol in ROMAN:
        while number >= value:
            result.append(symbol)
            number -= value
    return "".join(result)


def largest_prime_below(limit):
    for candidate in range(limit - 1, 1, -1):
        if all(candidate % d for d in range(2, int(candidate ** 0.5) + 1)):
            return candidate
    return None


def divisor_count(number):
    return sum(1 for d in range(1, number + 1) if number % d == 0)


def terminating_decimal(numerator, denominator):
    scaled = numerator * 10 ** 6 // denominator
    text = f"{scaled // 10 ** 6}.{scaled % 10 ** 6:06d}"
    return text.rstrip("0").rstrip(".")


