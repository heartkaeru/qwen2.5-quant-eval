def build_json():
    seen = set()

    def ex(prompt, expected, difficulty):
        add("json", "json", prompt, check="json", expected=expected,
            difficulty=difficulty, source="сгенерировано")

    def fill(count, factory):
        made = 0
        attempts = 0
        while made < count:
            attempts += 1
            if attempts > count * 1000:
                raise RuntimeError(f"Не удалось набрать {count} уникальных заданий.")
            item = factory()
            if item is None:
                continue
            prompt, expected, difficulty = item
            if prompt in seen:
                continue
            seen.add(prompt)
            ex(prompt, expected, difficulty)
            made += 1

    CITIES = [("Париж", "Франция"), ("Токио", "Япония"), ("Каир", "Египет"),
              ("Рим", "Италия"), ("Мадрид", "Испания"), ("Берлин", "Германия"),
              ("Осло", "Норвегия"), ("Сеул", "Южная Корея"), ("Варшава", "Польша"),
              ("Лиссабон", "Португалия"), ("Афины", "Греция"), ("Дублин", "Ирландия"),
              ("Будапешт", "Венгрия"), ("Прага", "Чехия"), ("Таллин", "Эстония"),
              ("Рейкьявик", "Исландия")]

    def pair_item():
        city, country = RNG.choice(CITIES)
        return (f'Верни только JSON-объект без Markdown с ключами "city" и "country". '
                f'Город — {city}, страна — {country}.', {"city": city, "country": country}, "easy")

    fill(10, pair_item)

    def extract_item():
        name = RNG.choice(["Анна", "Борис", "Вера", "Глеб", "Дина", "Егор", "Жанна", "Игорь"])
        age = RNG.randint(18, 70)
        city = RNG.choice(["Казань", "Пермь", "Омск", "Уфа", "Томск", "Сочи", "Курск"])
        return (f'Из текста «{name}, {age} лет, живёт в городе {city}» верни только JSON без Markdown '
                f'с ключами "name" (строка), "age" (число), "city" (строка).',
                {"name": name, "age": age, "city": city}, "medium")

    fill(10, extract_item)

    def sorted_array_item():
        numbers = RNG.sample(range(1, 99), RNG.randint(4, 6))
        listed = ", ".join(str(n) for n in numbers)
        return (f'Верни только JSON-массив без Markdown, отсортированный по возрастанию. '
                f'Исходные числа: {listed}.', sorted(numbers), "medium")

    fill(8, sorted_array_item)

    def nested_item():
        name = RNG.choice(["Анна", "Борис", "Вера", "Глеб", "Дина", "Егор"])
        age = RNG.randint(18, 70)
        return (f'Верни только JSON-объект без Markdown с ключом "user". Внутри "user" — ключи '
                f'"name" (строка) и "age" (число). Имя — {name}, возраст — {age}.',
                {"user": {"name": name, "age": age}}, "hard")

    fill(6, nested_item)

    def goods_item():
        items = RNG.sample([("хлеб", 45), ("молоко", 70), ("сыр", 300), ("чай", 150),
                            ("яйца", 110), ("масло", 220)], 3)
        described = "; ".join(f"{name} — {price} рублей" for name, price in items)
        expected = [{"name": name, "price": price} for name, price in items]
        return (f'Для товаров: {described}. Верни только JSON-массив объектов без Markdown, '
                f'у каждого объекта ключи "name" (строка) и "price" (число).', expected, "hard")

    fill(8, goods_item)

    def aggregate_item():
        numbers = RNG.sample(range(1, 50), RNG.randint(3, 6))
        listed = ", ".join(str(n) for n in numbers)
        return (f'Верни только JSON-объект без Markdown с ключами "sum" (сумма) и "count" (количество) '
                f'для чисел {listed}.',
                {"sum": sum(numbers), "count": len(numbers)}, "medium")

    fill(8, aggregate_item)

    def boolean_item():
        value = RNG.randint(2, 99)
        return (f'Верни только JSON-объект без Markdown с ключами "value" (число {value}) и '
                f'"even" (булево значение: чётное ли число).',
                {"value": value, "even": value % 2 == 0}, "medium")

    fill(6, boolean_item)

    def null_item():
        name = RNG.choice(["Анна", "Борис", "Вера", "Глеб", "Дина"])
        return (f'Верни только JSON-объект без Markdown: ключ "name" со значением "{name}" и '
                f'ключ "nickname" со значением null.', {"name": name, "nickname": None}, "hard")

    fill(5, null_item)

    def csv_item():
        rows = RNG.sample([("Анна", 20), ("Борис", 31), ("Вера", 27), ("Глеб", 44), ("Дина", 35)], 3)
        table = "name,age\\n" + "\\n".join(f"{name},{age}" for name, age in rows)
        expected = [{"name": name, "age": age} for name, age in rows]
        return (f'Дана таблица в формате CSV: «{table}». Верни только JSON-массив объектов без '
                f'Markdown с ключами "name" (строка) и "age" (число).', expected, "hard")

    fill(6, csv_item)

    def config_item():
        host = RNG.choice(["localhost", "example.com", "server.local", "api.test"])
        port = RNG.choice([80, 443, 8080, 5432, 6379])
        debug = RNG.choice([True, False])
        return (f'Верни только JSON-объект без Markdown: ключ "host" (строка "{host}"), '
                f'"port" (число {port}) и "debug" (булево {str(debug).lower()}).',
                {"host": host, "port": port, "debug": debug}, "hard")

    fill(6, config_item)


def build_instructions():
    seen = set()

    def ex(prompt, expected, difficulty):
        add("instructions", "instr", prompt, check="exact", expected=expected,
            difficulty=difficulty, source="сгенерировано")

    def fill(count, factory):
        made = 0
        attempts = 0
        while made < count:
            attempts += 1
            if attempts > count * 1000:
                raise RuntimeError(f"Не удалось набрать {count} уникальных заданий.")
            item = factory()
            if item is None:
                continue
            prompt, expected, difficulty = item
            if prompt in seen:
                continue
            seen.add(prompt)
            ex(prompt, expected, difficulty)
            made += 1

    def reverse_item():
        word = RNG.choice(WORDS)
        return (f"Напиши слово «{word}» в обратном порядке. Ответь только полученным словом.",
                word[::-1], "medium")

    fill(8, reverse_item)

    def sort_words_item():
        pool = [w for w in WORDS if "ё" not in w]
        words = RNG.sample(pool, 4)
        return ("Отсортируй слова по алфавиту и выведи через запятую с пробелом, без пояснений: "
                + ", ".join(words) + ".", ", ".join(sorted(words)), "medium")

    fill(8, sort_words_item)

    def sort_numbers_item():
        numbers = RNG.sample(range(1, 99), 5)
        return ("Отсортируй числа по возрастанию и выведи через запятую с пробелом, без пояснений: "
                + ", ".join(str(n) for n in numbers) + ".",
                ", ".join(str(n) for n in sorted(numbers)), "easy")

    fill(6, sort_numbers_item)

    def dedup_item():
        pool = RNG.sample(range(1, 30), 5)
        sequence = pool + pool[:2]
        RNG.shuffle(sequence)
        seen_once = list(dict.fromkeys(sequence))
        return ("Убери повторяющиеся числа, сохранив порядок первого появления, и выведи через запятую "
                "с пробелом, без пояснений: " + ", ".join(str(n) for n in sequence) + ".",
                ", ".join(str(n) for n in seen_once), "hard")

    fill(6, dedup_item)

    def no_spaces_item():
        phrase = " ".join(RNG.sample(WORDS, 3))
        return (f"Убери из строки «{phrase}» все пробелы и выведи результат без пояснений.",
                phrase.replace(" ", ""), "easy")

    fill(6, no_spaces_item)

    def count_letters_item():
        word = RNG.choice(WORDS)
        return (f"Сколько букв в слове «{word}»? Ответь только числом.", str(len(word)), "easy")

    fill(6, count_letters_item)

    def count_vowels_item():
        word = RNG.choice(WORDS)
        return (f"Сколько гласных букв в слове «{word}»? Ответь только числом.",
                str(sum(1 for ch in word if ch in VOWELS)), "medium")

    fill(6, count_vowels_item)

    def digits_item():
        code = RNG.randint(10000, 99999)
        stamp = f"{RNG.randint(1, 28):02d}.{RNG.randint(1, 12):02d}.{RNG.randint(1990, 2025)}"
        text = f"заказ №{code} от {stamp}"
        digits = "".join(ch for ch in text if ch.isdigit())
        return (f"Выпиши все цифры из строки «{text}» в том же порядке, без остальных символов.",
                digits, "hard")

    fill(6, digits_item)

    def edges_item():
        first, second = RNG.sample(WORDS, 2)
        return (f"Выведи первую букву слова «{first}» и последнюю букву слова «{second}» через дефис, "
                f"без пояснений.", f"{first[0]}-{second[-1]}", "hard")

    fill(6, edges_item)

    def repeat_item():
        word = RNG.choice(WORDS)
        times = RNG.randint(3, 6)
        return (f"Повтори слово «{word}» {times} раз через пробел и больше ничего не выводи.",
                " ".join([word] * times), "easy")

    fill(5, repeat_item)

    def join_item():
        parts = RNG.sample(WORDS, 4)
        separator = RNG.choice(["-", "_", "|", "+"])
        return ("Соедини слова " + ", ".join(f"«{p}»" for p in parts)
                + f" через разделитель «{separator}» без пробелов и без пояснений.",
                separator.join(parts), "medium")

    fill(5, join_item)

    def every_second_item():
        word = RNG.choice([w for w in WORDS if len(w) >= 5])
        return (f"Выведи каждую вторую букву слова «{word}», начиная с первой, без пробелов.",
                word[::2], "hard")

    fill(5, every_second_item)

    def reverse_order_item():
        words = RNG.sample(WORDS, 4)
        return ("Переставь слова в обратном порядке и выведи через пробел, без пояснений: "
                + " ".join(words) + ".", " ".join(reversed(words)), "medium")

    fill(5, reverse_order_item)

    def truncate_item():
        word = RNG.choice([w for w in WORDS if len(w) >= 6])
        keep = RNG.randint(3, 5)
        return (f"Выведи первые {keep} символа слова «{word}» без изменений и без пояснений.",
                word[:keep], "hard")

    fill(5, truncate_item)

    def count_words_item():
        phrase = " ".join(RNG.sample(WORDS, RNG.randint(3, 6)))
        return (f"Сколько слов в предложении «{phrase}»? Ответь только числом.",
                str(len(phrase.split())), "easy")

    fill(5, count_words_item)

    def replace_item():
        word = RNG.choice(WORDS)
        old = RNG.choice(list(dict.fromkeys(word)))
        new = RNG.choice([ch for ch in "абвгдежзиклмнопрстуфхцчшщэюя" if ch != old])
        replaced = word.replace(old, new)
        return (f"В слове «{word}» замени все буквы «{old}» на «{new}» и выведи результат без пояснений.",
                replaced, "hard")

    fill(6, replace_item)

    def occurrences_item():
        phrase = " ".join(RNG.sample(WORDS, 3))
        letter = RNG.choice([ch for ch in dict.fromkeys(phrase) if ch != " "])
        return (f"Сколько раз буква «{letter}» встречается в строке «{phrase}»? Ответь только числом.",
                str(phrase.count(letter)), "hard")

    fill(5, occurrences_item)


