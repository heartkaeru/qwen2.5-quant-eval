COUNTER = {}


def _next_id(prefix):
    COUNTER[prefix] = COUNTER.get(prefix, 0) + 1
    return f"{prefix}_{COUNTER[prefix]:03d}"


def add(category, prefix, prompt, check="exact", expected=None, rubric=None,
        difficulty="medium", source=None):
    task = {"id": _next_id(prefix), "category": category, "difficulty": difficulty,
            "check": check, "prompt": prompt}
    if check == "manual":
        task["rubric"] = rubric
    else:
        task["expected"] = expected
    if source:
        task["source"] = source
    TASKS.append(task)
    return task


def add_auto(category, prefix, prompt, expected, difficulty, source=None):
    """exact для строки, one_of для списка допустимых вариантов."""
    check = "one_of" if isinstance(expected, list) else "exact"
    return add(category, prefix, prompt, check=check, expected=expected,
               difficulty=difficulty, source=source)


